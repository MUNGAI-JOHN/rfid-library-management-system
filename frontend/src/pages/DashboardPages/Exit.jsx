import { useEffect, useState } from "react";
import { getExitLogs } from "../../api/exit.api";

import "./Exit.css";

function Exit() {
  const [logs, setLogs] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const loadExitLogs = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await getExitLogs();

      console.log("Exit logs:", response);

      if (response.success) {
        setLogs(response.data);
      }
    } catch (error) {
      console.error("Get exit logs error:", error);

      setError(error.response?.data?.message || "Failed to load exit logs.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadExitLogs();
  }, []);

  const formatDate = (date) => {
    if (!date) return "-";

    return new Date(date).toLocaleString("en-GB", {
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  };

  const authorizedCount = logs.filter((log) => log.bookAuthorized === true).length;

  const deniedCount = logs.filter((log) => log.bookAuthorized === false).length;

  return (
    <div className="exit-page">
      {/* HEADER */}

      <div className="exit-header">
        <div>
          <h1>Exit Logs</h1>

          <p>Monitor library exit activity and unauthorized books.</p>
        </div>

        <button className="refresh-button" onClick={loadExitLogs} disabled={loading}>
          {loading ? "Refreshing..." : "↻ Refresh"}
        </button>
      </div>

      {/* ERROR */}

      {error && <div className="error-message">{error}</div>}

      {/* STATISTICS */}

      <div className="exit-stats">
        <div className="stat-card">
          <p>Total Exit Attempts</p>
          <h2>{logs.length}</h2>
        </div>

        <div className="stat-card">
          <p>Authorized</p>
          <h2>{authorizedCount}</h2>
        </div>

        <div className="stat-card">
          <p>Denied</p>
          <h2>{deniedCount}</h2>
        </div>
      </div>

      {/* EXIT TABLE */}

      <div className="exit-card">
        <div className="table-header">
          <div>
            <h2>Exit History</h2>

            <p>Records generated by the library exit system.</p>
          </div>
        </div>

        {loading ? (
          <div className="loading-state">Loading exit logs...</div>
        ) : logs.length === 0 ? (
          <div className="empty-state">
            <h3>No exit records</h3>

            <p>Exit activity will appear here when patrons pass through the exit.</p>
          </div>
        ) : (
          <div className="table-container">
            <table>
              <thead>
                <tr>
                  <th>#</th>
                  <th>Patron RFID</th>
                  <th>Book RFID</th>
                  <th>Status</th>
                  <th>Exit Time</th>
                </tr>
              </thead>

              <tbody>
                {logs.map((log, index) => (
                  <tr key={log.id}>
                    <td>{index + 1}</td>

                    <td>
                      <strong>{log.patronRfid}</strong>
                    </td>

                    <td>{log.bookRfid || "No book"}</td>

                    <td>
                      {log.bookAuthorized ? (
                        <span className="status authorized">Authorized</span>
                      ) : (
                        <span className="status denied">Denied</span>
                      )}
                    </td>

                    <td>{formatDate(log.exitTime)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}

export default Exit;
