import { useEffect, useState } from "react";
import { getBorrowings } from "../../api/borrowing.api";

import "./Borrowing.css";

function Borrowing() {
  const [borrowings, setBorrowings] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  // =========================
  // LOAD BORROWINGS
  // =========================

  const loadBorrowings = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await getBorrowings();

      console.log("Borrowings:", response);

      if (response.success) {
        setBorrowings(response.data);
      }
    } catch (error) {
      console.error("Get borrowings error:", error);

      setError(error.response?.data?.message || "Failed to load borrowing records.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadBorrowings();
  }, []);

  // =========================
  // CALCULATE STATISTICS
  // =========================

  const activeBorrowings = borrowings.filter((borrowing) => !borrowing.returned);

  const returnedBorrowings = borrowings.filter((borrowing) => borrowing.returned);

  const overdueBorrowings = activeBorrowings.filter(
    (borrowing) => new Date(borrowing.dueDate) < new Date()
  );

  // =========================
  // FORMAT DATE
  // =========================

  const formatDate = (date) => {
    if (!date) return "-";

    return new Date(date).toLocaleDateString("en-GB", {
      day: "2-digit",
      month: "short",
      year: "numeric",
    });
  };

  // =========================
  // STATUS
  // =========================

  const getStatus = (borrowing) => {
    if (borrowing.returned) {
      return {
        text: "Returned",
        className: "status-returned",
      };
    }

    if (new Date(borrowing.dueDate) < new Date()) {
      return {
        text: "Overdue",
        className: "status-overdue",
      };
    }

    return {
      text: "Borrowed",
      className: "status-borrowed",
    };
  };

  return (
    <div className="borrowing-page">
      {/* =========================
          HEADER
      ========================= */}

      <div className="borrowing-header">
        <div>
          <h1>Borrowing</h1>

          <p>Monitor library borrowing records.</p>
        </div>

        <button className="refresh-button" onClick={loadBorrowings} disabled={loading}>
          {loading ? "Refreshing..." : "↻ Refresh"}
        </button>
      </div>

      {/* =========================
          ERROR
      ========================= */}

      {error && <div className="error-message">{error}</div>}

      {/* =========================
          STATISTICS
      ========================= */}

      <div className="borrowing-stats">
        <div className="stat-card">
          <div>
            <p>Active Borrowings</p>
            <h2>{activeBorrowings.length}</h2>
          </div>
        </div>

        <div className="stat-card">
          <div>
            <p>Returned Books</p>
            <h2>{returnedBorrowings.length}</h2>
          </div>
        </div>

        <div className="stat-card">
          <div>
            <p>Overdue Books</p>
            <h2>{overdueBorrowings.length}</h2>
          </div>
        </div>

        <div className="stat-card">
          <div>
            <p>Total Records</p>
            <h2>{borrowings.length}</h2>
          </div>
        </div>
      </div>

      {/* =========================
          BORROWING TABLE
      ========================= */}

      <div className="borrowing-card">
        <div className="table-header">
          <div>
            <h2>Borrowing Records</h2>

            <p>Records generated by the library borrowing system.</p>
          </div>
        </div>

        {loading ? (
          <div className="loading-state">Loading borrowing records...</div>
        ) : borrowings.length === 0 ? (
          <div className="empty-state">
            <h3>No borrowing records</h3>

            <p>Borrowing records will appear here when books are borrowed.</p>
          </div>
        ) : (
          <div className="table-container">
            <table>
              <thead>
                <tr>
                  <th>Patron</th>
                  <th>Book</th>
                  <th>Borrow Date</th>
                  <th>Due Date</th>
                  <th>Location</th>
                  <th>Status</th>
                </tr>
              </thead>

              <tbody>
                {borrowings.map((borrowing) => {
                  const status = getStatus(borrowing);

                  return (
                    <tr key={borrowing.id}>
                      {/* PATRON */}

                      <td>
                        <div className="patron-info">
                          <strong>{borrowing.patron?.fullName || borrowing.patronRfid}</strong>

                          <small>{borrowing.patron?.rfid_uid || borrowing.patronRfid}</small>
                        </div>
                      </td>

                      {/* BOOK */}

                      <td>
                        <div className="book-info">
                          <strong>{borrowing.book?.bookTitle || borrowing.bookRfid}</strong>

                          <small>{borrowing.book?.rfid_bid || borrowing.bookRfid}</small>
                        </div>
                      </td>

                      {/* BORROW DATE */}

                      <td>{formatDate(borrowing.borrowDate)}</td>

                      {/* DUE DATE */}

                      <td>{formatDate(borrowing.dueDate)}</td>

                      {/* LOCATION */}

                      <td>
                        <span className="location-badge">{borrowing.book?.location || "-"}</span>
                      </td>

                      {/* STATUS */}

                      <td>
                        <span className={`status-badge ${status.className}`}>{status.text}</span>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}

export default Borrowing;
